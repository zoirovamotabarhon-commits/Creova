let registered = false;

// Idempotent. Safe to call on every render: it only does work once i18n is initialized.
// Every supported language gets a bundle: its own translation if we have one,
// otherwise English. This does not depend on i18next's fallback behavior.
export function registerAiChatStrings(): void {
  if (registered || !i18n.isInitialized) return;
  for (const { code } of LANGUAGES) {
    i18n.addResourceBundle(code, "aiChat", AI_CHAT_STRINGS[code] ?? en, true, true);
  }
  registered = true;
  }
